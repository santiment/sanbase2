defmodule Sanbase.ShortUrl do
  use Ecto.Schema

  import Ecto.Query
  import Ecto.Changeset

  alias Sanbase.Repo

  @short_url_length 8
  @max_full_url_length 20_000
  @max_data_length 10_000
  @allowed_host_suffix "santiment.net"

  schema "short_urls" do
    field(:short_url, :string)
    field(:full_url, :string)
    field(:data, :string)

    belongs_to(:user, Sanbase.Accounts.User)

    timestamps()
  end

  def changeset(%__MODULE__{} = url, attrs \\ %{}) do
    url
    |> cast(attrs, [:full_url, :short_url, :user_id, :data])
    |> validate_required([:full_url, :short_url])
    |> validate_length(:full_url, max: @max_full_url_length)
    |> validate_length(:data, max: @max_data_length)
    |> validate_change(:full_url, &validate_full_url/2)
    |> unique_constraint(:short_url)
  end

  @doc false
  # The short url is resolved and followed by the frontend, so only a path on the
  # same site ("/charts?...") or an https url on a santiment.net host is accepted.
  # This rules out javascript:/data: schemes, arbitrary external hosts and
  # internal addresses.
  def validate_full_url(field, full_url) do
    case allowed_full_url?(full_url) do
      true -> []
      false -> [{field, "must be a relative path or an https url on #{@allowed_host_suffix}"}]
    end
  end

  defp allowed_full_url?("/" <> rest = url) do
    # Reject protocol-relative ("//host") and backslash ("/\\host") forms that
    # browsers treat as another host, and control characters.
    not String.starts_with?(rest, ["/", "\\"]) and not String.match?(url, ~r/[\x00-\x1f\x7f]/)
  end

  defp allowed_full_url?(url) do
    case URI.parse(url) do
      %URI{scheme: "https", host: host, userinfo: nil} when is_binary(host) ->
        host = String.downcase(host)
        (host == @allowed_host_suffix or String.ends_with?(host, "." <> @allowed_host_suffix)) and
          not String.match?(url, ~r/[\x00-\x20\x7f\\]/)

      _ ->
        false
    end
  end

  def create(%{full_url: full_url} = args) when is_binary(full_url) do
    user_id = Map.get(args, :user_id)
    data = Map.get(args, :data)
    hash_short_url = hash_short_url(full_url, data, user_id)

    # The short url is generated by the hash of the arguments, so multiple
    # invocations generate the same result.
    case Repo.get_by(__MODULE__, short_url: hash_short_url) do
      %__MODULE__{full_url: ^full_url, data: ^data, user_id: ^user_id} = url ->
        # In case the record exists just return it
        {:ok, url}

      %__MODULE__{} ->
        # In case of collision (it didn't match the previous clause) generate a random short url
        %__MODULE__{}
        |> changeset(Map.put(args, :short_url, random_short_url()))
        |> Repo.insert()

      nil ->
        %__MODULE__{}
        |> changeset(Map.put(args, :short_url, hash_short_url))
        |> Repo.insert()
    end
  end

  def update(user_id, short_url, params) do
    case get(short_url) do
      %__MODULE__{user_id: ^user_id} = struct ->
        struct
        |> changeset(params)
        |> Repo.update()

      _ ->
        {:error,
         "The Short URL #{short_url} does not exist or belongs to another user and cannot be updated"}
    end
  end

  def get(short_url) when is_binary(short_url) do
    from(
      url in __MODULE__,
      where: url.short_url == ^short_url
    )
    |> Repo.one()
  end

  defp hash_short_url(full_url, data, user_id) do
    :crypto.hash(:sha256, :erlang.term_to_binary({full_url, data, user_id}))
    |> Base.url_encode64(padding: false)
    |> binary_part(0, @short_url_length)
  end

  defp random_short_url() do
    :crypto.strong_rand_bytes(@short_url_length)
    |> Base.url_encode64(padding: false)
    |> binary_part(0, @short_url_length)
  end
end
